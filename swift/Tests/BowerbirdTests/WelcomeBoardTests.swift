import XCTest
@testable import BowerbirdCore

final class WelcomeBoardTests: XCTestCase {
    func testLoadsTheFullBoard() {
        let dir = URL(fileURLWithPath: "/tmp/welcome-test-board")
        guard let board = WelcomeBoard.board(for: dir) else {
            return XCTFail("the welcome board did not load")
        }
        XCTAssertEqual(board.items.count, 48)
        XCTAssertEqual(board.nextId, 48)
        XCTAssertEqual(board.nextGroup, 2)
        XCTAssertEqual(board.bg, "#FFFFFF")
        XCTAssertEqual(board.grid, .dots)
        XCTAssertEqual(board.camera.zoom, 1)
    }

    func testNoteHeightsMatchElectron() {
        let dir = URL(fileURLWithPath: "/tmp/welcome-test-board")
        guard let board = WelcomeBoard.board(for: dir) else {
            return XCTFail("the welcome board did not load")
        }
        // The heights come from Electron's estimateTextHeight
        // (the fixture was generated by running it), so they
        // must match exactly — a note that is too short clips
        // its text, one that is too tall leaves a gap.
        let heights = board.items.compactMap { item -> Double? in
            guard case .text = item.kind else { return nil }
            return item.size.h
        }
        XCTAssertEqual(heights, [137.6, 180.8, 200.0])
    }

    func testAssetPathsPointIntoTheBoardFolder() {
        let dir = URL(fileURLWithPath: "/tmp/welcome-test-board")
        guard let board = WelcomeBoard.board(for: dir) else {
            return XCTFail("the welcome board did not load")
        }
        // Every media path in the board must live under the
        // board folder (no placeholder left, no absolute path
        // from the machine that generated the fixture).
        let paths = board.items.compactMap { item -> String? in
            switch item.kind {
            case .image(let p): return p.path
            case .pdfCard(let p): return p.path
            case .audio(let p): return p.path
            case .video(let p): return p.source
            case .fileCard(let p): return p.path
            case .model3D(let p): return p.path
            default: return nil
            }
        }
        XCTAssertEqual(paths.count, 7)
        XCTAssertTrue(paths.allSatisfy { $0.hasPrefix("/tmp/welcome-test-board/") })
        XCTAssertFalse(paths.joined().contains(WelcomeBoard.boardDirPlaceholder))
    }

    func testEveryAssetShipsInTheBundle() {
        // The app copies each of these into the board folder
        // on seeding; a missing one leaves a media card with
        // nothing to show.
        for name in WelcomeBoard.assetNames {
            XCTAssertNotNil(WelcomeBoard.assetURL(named: name), "\(name) is missing from the bundle")
        }
    }
}
